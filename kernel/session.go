// sessionMain is the program of a session's worker: rbgo with the go-scikit
// bindings, answering one input at a time (runtime.ServeInterpreter).
const sessionMain = `// Code generated by go-notebook for notebook irb. DO NOT EDIT.

package main

import (
	"io"

	_nb "github.com/go-notebook/notebook/runtime"
	_rb "github.com/go-scikit/ruby/cells"
)

func main() {
	_nb.ServeInterpreter(func(out, errOut io.Writer) _nb.Interpreter { return _rb.NewWriting(out, errOut) })
}
`

// CompleteTimeout bounds how long a completion may take: the worker of a
// session whose completion runs longer (a receiver whose #methods does not
// return) is stopped, as a timed-out input's is.
var CompleteTimeout = 5 * time.Second

// Session is an interactive Ruby session, as irb is (notebook irb): inputs
// evaluated one at a time in one interpreter, any local assigned as often as
// wanted, `_` the last value. The interpreter runs in a worker process of
// its own, built once in the work directory, so an input that runs too long
// or holds too much memory (Options.CellTimeout and CellMemory, which apply
// to each input), or that is interrupted, has its worker killed while the
// session goes on — with a new worker, the state of the old one lost.
//
// A Session is not safe for concurrent use, except Interrupt, which may be
// called from another goroutine (a signal handler) while Eval runs.
type Session struct {
	k      *Kernel
	stderr io.Writer

	mu          sync.Mutex // guards worker against Interrupt
	worker      *exec.Cmd
	in          io.WriteCloser
	out         *bufio.Scanner
	interrupted atomic.Bool
	running     atomic.Bool // an input is being evaluated
	pending     []string    // output that came while no input ran
	notice      string      // why the last worker stopped outside an input
}

// Evaluation is the outcome of one input.
type Evaluation struct {
	Inspect string            // the value, as irb shows it
	Display map[string][]byte // the value's own display (a figure's SVG), if any
	Error   string            // the exception, "message (Class)" and its frames, or why the input was stopped
	Class   string            // the exception's class (SystemExit for exit)
	Lost    bool              // the input's worker was stopped: the session's state is gone
	Notice  string            // why an earlier worker stopped between inputs, if one did
	Took    time.Duration     // how long the input ran, in the worker
}

// NewSession prepares a session in opt.Dir — writing and building its worker
// when the work module is new or has changed, which progress is told about —
// and starts the worker. The kernel's other options apply as for a notebook:
// the runtime and go-scikit/ruby versions, the replaced modules, the limits.
func NewSession(opt Options, progress, stderr io.Writer) (*Session, error) {
	k, err := New(opt)
	if err != nil {
		return nil, err
	}
	k.langs = []string{analysis.Ruby}
	s := &Session{k: k, stderr: stderr}
	if err := s.build(progress); err != nil {
		return nil, err
	}
	if err := s.start(); err != nil {
		return nil, err
	}
	return s, nil
}

// build writes the worker's module and compiles it, unless the binary in
// the work directory was built from the same go.mod and program. With a
// replaced module (a local checkout) it always builds: the checkout may have
// changed.
func (s *Session) build(progress io.Writer) error {
	dir := s.k.opt.Dir
	mod := s.k.goMod()
	stamp := sessionStamp(mod)
	stampPath := filepath.Join(dir, "worker.stamp")
	if len(s.k.opt.Replace) == 0 {
		if b, err := os.ReadFile(stampPath); err == nil && string(b) == stamp {
			if _, err := os.Stat(s.k.binary()); err == nil {
				return nil
			}
		}
	}
	fmt.Fprintln(progress, "notebook irb: building the Ruby worker (once; later sessions reuse it)")
	if err := writeFile(filepath.Join(dir, "go.mod"), []byte(mod), 0o644); err != nil {
		return err
	}
	if err := writeFile(filepath.Join(dir, "main.go"), []byte(sessionMain), 0o644); err != nil {
		return err
	}
	if out, err := s.k.goCmd("mod", "tidy").CombinedOutput(); err != nil {
		return fmt.Errorf("go mod tidy: %v\n%s", err, out)
	}
	if out, err := goBuild(dir, s.k.binary()); err != nil {
		return fmt.Errorf("build: %v\n%s", err, out)
	}
	return writeFile(stampPath, []byte(stamp), 0o644)
}

// sessionStamp identifies a worker built from the work module mod.
func sessionStamp(mod string) string {
	sum := sha256.Sum256([]byte(mod + "\x00" + sessionMain))
	return hex.EncodeToString(sum[:])
}

// start launches a worker, in a process group of its own: Ctrl-C in the
// terminal reaches the session, which decides to stop the worker
// (Interrupt), not the worker directly.
func (s *Session) start() error {
	cmd := exec.Command(s.k.binary())
	cmd.Dir = s.k.opt.Dir
	cmd.Stderr = s.stderr
	cmd.SysProcAttr = ownProcessGroup()
	if s.k.opt.CellMemory > 0 {
		cmd.Env = append(os.Environ(), fmt.Sprintf("%s=%d", runtime.MemoryEnv, s.k.opt.CellMemory))
	}
	// The pipes fail only when Stdin or Stdout is already set.
	in, _ := cmd.StdinPipe()
	out, _ := cmd.StdoutPipe()
	if err := cmd.Start(); err != nil {
		return fmt.Errorf("the Ruby worker did not start: %w", err)
	}
	sc := bufio.NewScanner(out)
	sc.Buffer(make([]byte, 1<<20), 1<<30)
	s.mu.Lock()
	s.worker, s.in, s.out = cmd, in, sc
	s.mu.Unlock()
	return nil
}

// Eval evaluates one input, which starts at line of the session (the line
// numbers of its backtraces), and hands what it prints to output as it is
// printed. A worker that a previous input or completion stopped is replaced
// first.
func (s *Session) Eval(src string, line int, output func(string)) Evaluation {
	var ev Evaluation
	ev.Notice, s.notice = s.notice, ""
	for _, p := range s.pending {
		output(p)
	}
	s.pending = nil
	if s.worker == nil {
		if err := s.start(); err != nil {
			ev.Error, ev.Lost = err.Error(), true
			return ev
		}
	}
	s.interrupted.Store(false)
	var timedOut atomic.Bool
	if d := s.k.opt.CellTimeout; d > 0 {
		t := time.AfterFunc(d, func() {
			timedOut.Store(true)
			s.kill()
		})
		defer t.Stop()
	}
	s.running.Store(true)
	rep, err := s.call(runtime.Request{Op: "eval", Source: src, Line: line}, output)
	s.running.Store(false)
	if err != nil {
		ev.Error, ev.Lost = s.died(err, timedOut.Load(), "input"), true
		return ev
	}
	ev.Inspect, ev.Error, ev.Class, ev.Took = rep.Inspect, rep.Error, rep.Class, rep.Took
	if len(rep.Display) > 0 {
		ev.Display = rep.Display[0]
	}
	return ev
}

// Complete returns the completions of target, the word before the cursor;
// none when the worker cannot say. A completion that takes longer than
// CompleteTimeout stops the worker, and the next Eval says so.
func (s *Session) Complete(target string) []string {
	if s.worker == nil {
		return nil
	}
	var timedOut atomic.Bool
	t := time.AfterFunc(CompleteTimeout, func() {
		timedOut.Store(true)
		s.kill()
	})
	defer t.Stop()
	rep, err := s.call(runtime.Request{Op: "complete", Source: target}, func(o string) { s.pending = append(s.pending, o) })
	if err != nil {
		why := s.died(err, false, "completion")
		if timedOut.Load() {
			why = fmt.Sprintf("stopped: completing %q took longer than %s; its worker was killed", target, CompleteTimeout)
		}
		s.notice = why
		return nil
	}
	return rep.Candidates
}

// Interrupt stops the input that is running, by killing its worker (rbgo
// cannot be interrupted in the middle of an evaluation); Eval then reports
// it. It does nothing between inputs.
func (s *Session) Interrupt() {
	if s.running.Load() {
		s.interrupted.Store(true)
		s.kill()
	}
}

// kill kills the worker, if any.
func (s *Session) kill() {
	s.mu.Lock()
	defer s.mu.Unlock()
	if s.worker != nil {
		_ = s.worker.Process.Kill()
	}
}

// call sends a request and reads replies up to the one that ends it, handing
// the output that comes before it to output. An error means the worker
// stopped answering.
func (s *Session) call(req runtime.Request, output func(string)) (runtime.Reply, error) {
	b, _ := json.Marshal(req) // a Request always marshals
	if _, err := s.in.Write(append(b, '\n')); err != nil {
		return runtime.Reply{}, err
	}
	for {
		if !s.out.Scan() {
			err := s.out.Err()
			if err == nil {
				err = io.EOF
			}
			return runtime.Reply{}, err
		}
		var rep runtime.Reply
		if err := json.Unmarshal(s.out.Bytes(), &rep); err != nil {
			return runtime.Reply{}, fmt.Errorf("bad reply: %v", err)
		}
		if rep.More {
			output(rep.Output)
			continue
		}
		return rep, nil
	}
}

// died stops a worker that stopped answering during what (an input, a
// completion) and says why it stopped.
func (s *Session) died(err error, timedOut bool, what string) string {
	code := s.stop()
	switch {
	case timedOut:
		return fmt.Sprintf("stopped: the %s ran longer than %s, the limit; its worker was killed", what, s.k.opt.CellTimeout)
	case s.interrupted.Load():
		return fmt.Sprintf("interrupted: the %s was stopped by killing its worker", what)
	case code == runtime.ExitMemory:
		return fmt.Sprintf("stopped: the %s went over the memory limit of %d MiB; its worker was killed", what, s.k.opt.CellMemory>>20)
	}
	return "the worker stopped: " + err.Error()
}

// stop ends the worker, if any, and returns its exit status.
func (s *Session) stop() int {
	s.mu.Lock()
	cmd := s.worker
	s.worker = nil
	s.mu.Unlock()
	if cmd == nil {
		return 0
	}
	_, _ = s.in.Write([]byte(`{"op":"exit"}` + "\n"))
	_ = s.in.Close()
	err := cmd.Wait()
	var ee *exec.ExitError
	if errors.As(err, &ee) {
		return ee.ExitCode()
	}
	return 0
}

// Close ends the session's worker.
func (s *Session) Close() error {
	s.stop()
	return nil
}
